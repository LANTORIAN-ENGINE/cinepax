// ─── Résolution + interpolation ───────────────────────────────────────────────
function resolve(dict, path) {
  return path.split('.').reduce((o, k) => (o == null ? o : o[k]), dict)
}

function interpolate(str, vars) {
  if (!vars) return str
  return str.replace(/\{(\w+)\}/g, (_, k) => (vars[k] != null ? vars[k] : `{${k}}`))
}

export function translate(lang, key, vars) {
  let val = resolve(DICT[lang], key)
  if (val == null) val = resolve(DICT.fr, key)   // repli sur le français
  if (val == null) return key
  if (typeof val === 'object' && (val.one || val.other)) {
    const count = vars?.count ?? vars?.n ?? vars?.assigned
    val = Number(count) === 1 ? val.one : val.other
  }
  return interpolate(val, vars)
}

// ─── Contexte React ───────────────────────────────────────────────────────────
const LangContext = createContext(null)
const STORAGE_KEY = 'cinepax_lang'

export function LanguageProvider({ children }) {
  const [lang, setLangState] = useState('fr')

  useEffect(() => {
    const saved = typeof window !== 'undefined' ? localStorage.getItem(STORAGE_KEY) : null
    if (saved === 'fr' || saved === 'en') setLangState(saved)
  }, [])

  useEffect(() => {
    if (typeof document !== 'undefined') document.documentElement.lang = lang
  }, [lang])

  function setLang(next) {
    setLangState(next)
    try { localStorage.setItem(STORAGE_KEY, next) } catch {}
  }

  const value = {
    lang,
    setLang,
    t: (key, vars) => translate(lang, key, vars),
    locale: LOCALES[lang].date,
    moneyLocale: LOCALES[lang].money,
  }

  return <LangContext.Provider value={value}>{children}</LangContext.Provider>
}

export function useI18n() {
  const ctx = useContext(LangContext)
  if (!ctx) {
    // Repli hors provider : français statique, pas de persistance
    return {
      lang: 'fr',
      setLang: () => {},
      t: (key, vars) => translate('fr', key, vars),
      locale: LOCALES.fr.date,
      moneyLocale: LOCALES.fr.money,
    }
  }
  return ctx
}
